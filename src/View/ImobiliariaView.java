    // Implementação do CRUD (fora do trecho gerado pelo NetBeans).
    private String lerCampo(JTextField campo, String placeholder) {
        String valor = campo.getText().trim();
        return valor.equals(placeholder) ? "" : valor;
    }

    private ImobiliariasModel dadosDoFormulario() {
        ImobiliariasModel imob = new ImobiliariasModel();
        imob.setID(idSelecionado);
        imob.setNome(lerCampo(txtNomeImobiliaria, "Digite o nome"));
        imob.setTelefone(lerCampo(txtTelefone, "(00) 00000-0000"));
        imob.setContato(lerCampo(txtContato, "Nome do responsável"));
        return imob;
    }

    private void mostrarErro(Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
    }

    private void limpar() {
        idSelecionado = 0;
        txtNomeImobiliaria.setText("Digite o nome");
        txtTelefone.setText("(00) 00000-0000");
        txtContato.setText("Nome do responsável");
    }

    private void cadastrar() {
        try {
            int id = controller.cadastrar(dadosDoFormulario());
            JOptionPane.showMessageDialog(this, "Imobiliária cadastrada! ID: " + id);
            limpar();
        } catch (SQLException | IllegalArgumentException e) {
            mostrarErro(e);
        }
    }

    private void consultar() {
        try {
            List<ImobiliariasModel> lista = controller.listar();
            Object[][] dados = new Object[lista.size()][4];
            for (int i = 0; i < lista.size(); i++) {
                ImobiliariasModel imob = lista.get(i);
                dados[i] = new Object[]{imob.getID(), imob.getNome(), imob.getTelefone(), imob.getContato()};
            }
            int id = Catalogo.selecionar(this, "Catálogo de imobiliárias",
                    new String[]{"ID", "Nome", "Telefone", "Contato"}, dados);
            if (id == 0) return;
            ImobiliariasModel imob = controller.buscarPorId(id);
            if (imob == null) {
                JOptionPane.showMessageDialog(this, "Imobiliária não encontrada.");
                return;
            }
            idSelecionado = imob.getID();
            txtNomeImobiliaria.setText(imob.getNome());
            txtTelefone.setText(imob.getTelefone());
            txtContato.setText(imob.getContato());
        } catch (SQLException e) {
            mostrarErro(e);
        }
    }

    private void atualizar() {
        if (idSelecionado == 0) {
            JOptionPane.showMessageDialog(this, "Consulte e selecione uma imobiliária antes de atualizar.");
            return;
        }
        try {
            if (controller.atualizar(dadosDoFormulario())) {
                JOptionPane.showMessageDialog(this, "Imobiliária atualizada!");
                limpar();
            } else {
                JOptionPane.showMessageDialog(this, "Registro não encontrado.");
                limpar();
            }
        } catch (SQLException | IllegalArgumentException e) {
            mostrarErro(e);
        }
    }

    private void excluir() {
        if (idSelecionado == 0) {
            JOptionPane.showMessageDialog(this, "Consulte e selecione uma imobiliária antes de excluir.");
            return;
        }
        if (JOptionPane.showConfirmDialog(this, "Excluir a imobiliária ID " + idSelecionado + "?",
                "Confirmar exclusão", JOptionPane.YES_NO_OPTION) != JOptionPane.YES_OPTION) return;
        try {
            if (controller.excluir(idSelecionado))
                JOptionPane.showMessageDialog(this, "Imobiliária excluída!");
            else JOptionPane.showMessageDialog(this, "Registro não encontrado.");
            limpar();
        } catch (SQLException | IllegalStateException e) {
            mostrarErro(e);
        }
    }

